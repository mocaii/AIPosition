import { test, expect } from '@playwright/test';
import { loadContent, publicContent } from '../../scripts/content.mjs';
const content = publicContent(await loadContent());
const fdeResources = content.roles.find(r => r.id === 'P001').resources;
const chineseFdeCount = fdeResources.filter(ref => /中文|中英/.test(content.resources.find(r => r.id === ref.id).language)).length;
test('岗位搜索、分类、详情与返回', async ({page}) => {
  await page.goto('/');
  await expect(page.locator('#role-grid>.role-card')).toHaveCount(content.roles.length);
  await page.locator('#search').fill('ｆｄｅ');
  await expect(page).toHaveURL(/q=/);
  await expect(page.locator('#role-grid>.role-card:visible')).toHaveCount(3);
  await page.locator('#role-grid [data-id="P001"] .card-title').click();
  await expect(page.locator('#role-dialog')).toBeVisible();
  await expect(page.locator('#drawer-body .resource-row')).toHaveCount(fdeResources.length);
  await page.locator('#drawer-body [data-resource-filter="chinese"]').click();
  await expect(page.locator('#drawer-body .resource-row:visible')).toHaveCount(chineseFdeCount);
  await page.keyboard.press('Escape');
  await expect(page.locator('#role-dialog')).not.toBeVisible();
  await expect(page).not.toHaveURL(/role=/);
  await expect(page.locator('#search')).toHaveValue('ｆｄｅ');
  await page.locator('.clear-filters').first().click();
  await page.locator('.category-nav [data-category="C02"]').click();
  await expect(page.locator('#role-grid>.role-card:visible')).toHaveCount(content.roles.filter(r => r.category === 'C02').length);
});
test('资料筛选、无结果、直达详情和技能专题', async ({page}) => {
  await page.goto('/resources/');
  await expect(page.locator('.resource-list>.resource-row')).toHaveCount(content.resources.length);
  await page.locator('#search').fill('hello agents');
  await expect(page.locator('.resource-list>.resource-row:visible')).toHaveCount(1);
  await page.locator('#language').selectOption('english');
  await expect(page.locator('#empty')).toBeVisible();
  await page.locator('#language').selectOption('chinese');
  await page.locator('.resource-row:visible h3').click();
  await expect(page.locator('h1')).toHaveText('Hello Agents');
  await page.getByRole('link',{name:'智能体',exact:true}).click();
  await expect(page).toHaveURL(/\/skills\/agent\//);
  await expect(page.locator('h1')).toHaveText('智能体');
});
test('局部图谱、分享筛选和跨类型搜索', async ({page}) => {
  await page.goto('/?view=graph&skill=rag');
  await expect(page.locator('#graph-panel')).toBeVisible();
  await expect(page.locator('.network .node.center')).toHaveText('检索增强生成');
  await expect(page.locator('.network .node.role-open')).toHaveCount(Math.min(8, content.roles.filter(r => r.skill_ids.includes('rag')).length));
  await page.locator('[data-view="cards"]').click();
  await expect(page.locator('#role-grid')).toBeVisible();
  await page.locator('.clear-filters').first().click();
  await page.locator('#search').fill('Hello Agents');
  await expect(page.locator('#cross-results')).toBeVisible();
  await expect(page.locator('#cross-results')).toContainText('Hello Agents');
});
test('手机布局无横向溢出，岗位以完整页面打开', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#role-grid [data-id="P001"] .card-title').click();
  await expect(page).toHaveURL(/\/roles\/p001-/);
  await expect(page.locator('h1')).toHaveText('FDE');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/resources/');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('截取桌面与手机交付预览', async ({page}) => {
  await page.goto('/');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path:'test-results/home-desktop.png',fullPage:false,animations:'disabled'});
  await page.locator('#role-grid [data-id="P001"] .card-title').click();
  await expect(page.locator('#drawer-body .resource-row')).toHaveCount(fdeResources.length);
  await page.screenshot({path:'test-results/fde-drawer.png',fullPage:false,animations:'disabled'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.screenshot({path:'test-results/home-mobile.png',fullPage:false,animations:'disabled'});
});
